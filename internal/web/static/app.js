// serverTile renders a server's icon tile: an uploaded image, a preset block
// texture, or the server's initials as a fallback.
function serverTile(s, size = 30) {
	if (s.icon_image) {
		return `<img class="tile-img" style="width:${size}px;height:${size}px"
			src="/api/servers/${esc(s.id)}/icon" alt="" onerror="this.style.display='none'">`;
	}
	if (s.icon && SERVER_ICONS[s.icon]) {
		return `<img class="tile-block" style="width:${size}px;height:${size}px"
			src="/static/blocks/${esc(s.icon)}.png" alt="${esc(SERVER_ICONS[s.icon])}">`;
	}
	const words = s.name.replace(/[^A-Za-z0-9 ]/g, "").trim().split(/\s+/);
	const initials = esc((words.length > 1 ? words.slice(0, 2).map((w) => w[0]) : [s.name[0]]).join("").toUpperCase());
	return `<span class="tile-initials" style="width:${size}px;height:${size}px;font-size:${Math.round(size * 0.36)}px">${initials}</span>`;
}

// blockIcon renders one preset block texture for the picker grid.
