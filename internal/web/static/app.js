/* ---------------------------------------------------------------- console */
function appendLine(line) {
	const box = $("#console");
	const nearBottom = box.scrollHeight - box.scrollTop - box.clientHeight < 40;
	const el = document.createElement("span");
	el.className = `ln ${esc(line.level || "info")}`;
	const t = new Date(line.time);
	el.innerHTML = `<span class="t">${t.toLocaleTimeString()}</span>${esc(line.text)}`;
	box.appendChild(el);
	if (state.consoleLines++ > 1500) {
		box.firstElementChild?.remove();
		state.consoleLines--;
	}
	if (nearBottom) box.scrollTop = box.scrollHeight;
}

async function loadHistory(id) {
	const box = $("#console");
	box.innerHTML = "";
	state.consoleLines = 0;
	try {
		const hist = await api(`/api/servers/${id}/console/history`);
		(hist || []).forEach(appendLine);
	} catch { /* server may be gone */ }
}

function connectConsole(id) {
	if (state.sse) { state.sse.close(); state.sse = null; }
	const es = new EventSource(`/api/servers/${id}/console`);
	es.onmessage = (e) => {
		try { appendLine(JSON.parse(e.data)); } catch { /* ignore */ }
	};
	state.sse = es;
}

async function selectServer(id) {
	state.selected = id;
	renderSidebar();
	renderHeader();
	await loadHistory(id);
	connectConsole(id);
	switchTab(state.tab);
}

